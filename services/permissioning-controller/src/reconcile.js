'use strict';

/**
 * Pure reconciliation: registry state in, permissions file out.
 *
 * Kept free of IO so it can be tested without a chain. Every interesting
 * decision about who may connect lives here.
 */

/**
 * Computes the desired allowlists from the registry's view of membership.
 *
 * RECONCILIATION, NOT DELTAS. The controller does not translate events into
 * add and remove calls. It reads the whole registry, computes what the file
 * should contain, and writes that.
 *
 * The difference matters when the controller has been down. Delta application
 * drifts: miss one event and the allowlist is permanently wrong with nothing
 * to detect it. Reconciliation is idempotent, so a controller that missed an
 * hour catches up by doing exactly what it always does, and a node that
 * restarts reads correct state from the file without needing a replay.
 *
 * Events are therefore a trigger to reconcile, never the data.
 *
 * @param {Array<{id: string, status: number, enodes: string[], accounts: string[]}>} members
 * @param {object} opts
 * @param {string[]} opts.infrastructureEnodes nodes that belong to no member
 * @param {string[]} opts.infrastructureAccounts accounts that belong to no member
 * @returns {{nodes: string[], accounts: string[]}}
 */
function desiredAllowlists(members, opts = {}) {
  const ACTIVE = 1; // IMemberRegistry.Status.Active

  const nodes = new Set((opts.infrastructureEnodes || []).map(normaliseEnode));

  // Accounts belonging to no member: the operator's deployer and services.
  // These are a standing privilege granted by static configuration rather than
  // by vote, which is a real weakness and is named as one in the threat model
  // rather than hidden. Without them, enabling account permissioning would
  // lock out the only account able to deploy, and the registry has no concept
  // of an operator tool.
  const accounts = new Set((opts.infrastructureAccounts || []).map((a) => a.toLowerCase()));

  for (const m of members) {
    // Suspended and Removed both lose access. The registry keeps the
    // distinction for its own audit trail; from the allowlist's point of view
    // anything that is not Active is out.
    if (Number(m.status) !== ACTIVE) continue;
    for (const e of m.enodes || []) nodes.add(normaliseEnode(e));
    for (const a of m.accounts || []) accounts.add(a.toLowerCase());
  }

  return {
    nodes: [...nodes].sort(),
    accounts: [...accounts].sort(),
  };
}

/**
 * Besu compares enode URLs as strings, so casing and whitespace matter. The
 * public key is hex and arrives in mixed case from different sources.
 */
function normaliseEnode(enode) {
  const trimmed = String(enode).trim();
  const at = trimmed.indexOf('@');
  if (at < 0) return trimmed;
  return trimmed.slice(0, at).toLowerCase() + trimmed.slice(at);
}

/**
 * Renders the TOML Besu expects.
 *
 * A malformed file is rejected wholesale by perm_reloadPermissionsFromFile and
 * the running node keeps its previous allowlist, so a bad write fails safe
 * rather than locking the consortium out. That is verified behaviour on
 * 26.8.1, not an assumption, and it is why this function does not need to
 * validate its own output.
 */
function renderToml({ nodes, accounts }, meta = {}) {
  const lines = [
    '# Generated by the permissioning controller. Do not edit by hand.',
    '#',
    '# The authority for membership is the on-chain MemberRegistry. This file is',
    '# an enforcement point with a propagation delay, not an authorisation',
    '# boundary. See ADR 0006.',
  ];
  if (meta.block !== undefined) lines.push(`# Reconciled at block ${meta.block}.`);
  if (meta.registry) lines.push(`# Registry ${meta.registry}.`);
  lines.push('');
  lines.push(`nodes-allowlist=${toTomlArray(nodes)}`);
  lines.push(`accounts-allowlist=${toTomlArray(accounts)}`);
  lines.push('');
  return lines.join('\n');
}

function toTomlArray(values) {
  if (values.length === 0) return '[]';
  return '[' + values.map((v) => `"${v}"`).join(',') + ']';
}

/** True when the rendered content differs from what is already on disk. */
function changed(previous, next) {
  return stripComments(previous) !== stripComments(next);
}

/**
 * Comments carry the block number, which changes on every poll. Comparing
 * without them means the file is rewritten and reloaded only when the
 * allowlists actually differ, rather than every few seconds.
 */
function stripComments(text) {
  return String(text || '')
    .split('\n')
    .filter((l) => !l.trimStart().startsWith('#'))
    .join('\n')
    .trim();
}

/**
 * Refuses an allowlist that would exclude a node the network is configured to
 * connect to.
 *
 * This is an invariant, not a configuration preference, and it is enforced
 * here for the same reason the validator floor lives in the registry rather
 * than the governor: the component that can cause the damage refuses, instead
 * of relying on whoever configures it upstream being careful.
 *
 * The failure it prevents is specifically nasty. Besu will not start when a
 * static node is missing from its allowlist, and a running controller
 * overwrites a hand-corrected file within one reconcile interval. So the
 * symptom is a node refusing to start, citing a file that looks correct by the
 * time anyone reads it, with the correction being silently undone faster than
 * it can be made. That cost twenty minutes to diagnose once and would cost it
 * again.
 *
 * @param {{nodes: string[]}} desired
 * @param {string[]} staticNodes every enode in static-nodes.json
 * @returns {string[]} the enodes that would be excluded, empty when safe
 */
function missingStaticNodes(desired, staticNodes) {
  const allowed = new Set(desired.nodes.map(normaliseEnode));
  return (staticNodes || [])
    .map(normaliseEnode)
    .filter((enode) => !allowed.has(enode));
}

module.exports = { desiredAllowlists, renderToml, changed, normaliseEnode, missingStaticNodes };
