#!/usr/bin/env bash
#
# Prepares a Kubernetes deployment from the generated PKI and chain material.
#
# Copies the genesis and permissions file into the chart's files/ directory,
# writes the node public keys into a values override, and creates the two
# secrets holding key material.
#
# KEY MATERIAL IS NEVER TEMPLATED FROM VALUES. A values file ends up in shell
# history, CI logs and Helm's own release storage, so secrets are created
# directly with kubectl and the chart only references them by name.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$REPO/tools/lib/env.sh"
env_init "$REPO"

CHART="$REPO/deploy/helm/besu-consortium"
NS="${K8S_NAMESPACE:-loc-consortium}"
PKI="$REPO/network/pki/out"

command -v kubectl >/dev/null || { echo "kubectl is required"; exit 1; }
[[ -f "$ENV_GENESIS" ]]  || { echo "no genesis for $ENV_NAME; run make network-keys"; exit 1; }
[[ -f "$ENV_MANIFEST" ]] || { echo "no manifest for $ENV_NAME"; exit 1; }
[[ -d "$PKI/keystores" ]] || { echo "no keystores; run make pki"; exit 1; }

mkdir -p "$CHART/files"

echo "==> chart files"

# THE GENESIS IS COPIED WITHOUT ITS TRANSITIONS BLOCK, DELIBERATELY.
#
# The local chain's genesis carries a transitions entry moving QBFT to contract
# validator selection at block 17300. From that block every node reads the
# validator set from ValidatorSetView and expects the header extraData to
# contain NO validators.
#
# A fresh chain started from that genesis fails at block 1 with "Validators in
# extra data expected to be empty", because the genesis extraData embeds all
# four and the proposer builds block 1 the same way. It worked on Compose only
# because seventeen thousand blocks of header-based history came first, and the
# contract was deployed long before the transition fired.
#
# So this deployment starts in header-voting mode, exactly as the Compose
# network did, and moving it to contract validator selection is a day-two
# operation with its own runbook entry rather than something baked into a
# fresh install. Making the chart depend on contract deployment order would be
# the wrong coupling: the chart deploys a network, it does not deploy
# governance.
#
# KEEP_TRANSITIONS=1 copies the genesis unchanged, which is correct when
# restoring a cluster onto an existing chain whose contracts are already
# deployed.
if [[ "${KEEP_TRANSITIONS:-0}" == "1" ]]; then
  cp "$ENV_GENESIS" "$CHART/files/genesis.json"
  echo "    genesis.json (transitions kept)"
else
  jq 'del(.config.transitions)' "$ENV_GENESIS" > "$CHART/files/genesis.json"
  if jq -e '.config.transitions' "$ENV_GENESIS" >/dev/null 2>&1; then
    echo "    genesis.json (transitions stripped: fresh chain starts in header-voting mode)"
  else
    echo "    genesis.json"
  fi
fi
if [[ -f "$ENV_CONFIG_DIR/permissions.toml" ]]; then
  cp "$ENV_CONFIG_DIR/permissions.toml" "$CHART/files/permissions.toml"
else
  "$REPO/tools/gen-permissions.sh" >/dev/null
  cp "$ENV_CONFIG_DIR/permissions.toml" "$CHART/files/permissions.toml"
fi
echo "    permissions.toml"

echo "==> node public keys"
# The chart needs each node's devp2p public key to build enode URLs. The IP
# addresses are resolved in-cluster at startup; the keys are known now.
{
  echo "# Generated by tools/k8s-prepare.sh from the $ENV_NAME manifest."
  echo "# Public keys only. No private key material belongs in a values file."
  echo "nodes:"
  for entry in "validator-importer:validator-1.importer-bank" \
               "validator-exporter:validator-1.exporter-bank" \
               "validator-logistics:validator-1.logistics" \
               "validator-operator:validator-1.operator" \
               "rpc-1:rpc-1.operator" \
               "rpc-2:rpc-2.operator"; do
    short="${entry%%:*}"
    full="${entry##*:}"
    pub="$(jq -r --arg n "$full" '.nodes[] | select(.node==$n) | .pubkey' "$ENV_MANIFEST")"
    [[ -n "$pub" && "$pub" != "null" ]] || { echo "no pubkey for $full in the manifest" >&2; exit 1; }
    org="${full#*.}"
    role=validator
    [[ "$short" == rpc-* ]] && role=rpc
    echo "  - name: $short"
    echo "    certName: $full"
    echo "    org: $org"
    echo "    role: $role"
    echo "    pubkey: \"${pub#0x}\""
  done
} > "$CHART/values-nodes.yaml"
echo "    wrote $CHART/values-nodes.yaml"

echo "==> namespace"
kubectl create namespace "$NS" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
echo "    $NS"

echo "==> secrets"
# Keystores: every node's PKCS12, the shared truststore and the password.
# Mounted whole rather than per node, which is a deliberate simplification for
# a single-tenant cluster and is NOT what the Compose stack does: there each
# node mounts only its own keystore, so one node cannot read another's private
# key. In a real deployment each organisation runs its own cluster and mounts
# only its own, and this is the first thing to change when that is true.
kubectl -n "$NS" create secret generic besu-keystores \
  --from-file="$PKI/keystores" \
  --dry-run=client -o yaml | kubectl apply -f - >/dev/null

# Node keys, one file per node named by its certificate name.
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
for d in "$ENV_KEYS_DIR"/*/; do
  name="$(basename "$d")"
  [[ "$name" == "members" || "$name" == "deployer" ]] && continue
  [[ -f "$d/key.priv" ]] && cp "$d/key.priv" "$TMP/$name"
done
kubectl -n "$NS" create secret generic besu-node-keys \
  --from-file="$TMP" \
  --dry-run=client -o yaml | kubectl apply -f - >/dev/null
echo "    besu-keystores, besu-node-keys"

echo
echo "ready. install with:"
echo "  helm upgrade --install loc $CHART \\"
echo "    --namespace $NS \\"
echo "    -f $CHART/values-kind.yaml \\"
echo "    -f $CHART/values-nodes.yaml"
