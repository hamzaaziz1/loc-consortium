#!/usr/bin/env bash
#
# Writes the INITIAL permissions file for an environment.
#
# Besu refuses to start when --permissions-*-config-file-enabled is set and the
# file is absent, so the file has to exist before the nodes do. The controller
# cannot produce it: it reads the registry over RPC, and there is no RPC to read
# until the nodes are up.
#
# So the bootstrap order is: this script writes a file from static config, the
# nodes start, the controller reconciles it against the chain from then on.
#
# The allowlist is network-wide rather than per-node, so one file serves all
# six. Node permissioning in Besu is each node deciding who it will talk to,
# and in a consortium every node should reach the same answer.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$REPO/tools/lib/env.sh"
env_init "$REPO"

OUT="$ENV_CONFIG_DIR/permissions.toml"

[[ -f "$ENV_STATIC_NODES" ]] || { echo "no static nodes. run gen-static-nodes.sh first"; exit 1; }

nodes="$(jq -c '[.[]]' "$ENV_STATIC_NODES")"

# Accounts come from deploy.json when it exists. Before deployment there are no
# member accounts to allow, and an empty accounts allowlist means nothing can
# transact, so account permissioning stays off until the controller enables it.
if [[ -f "$ENV_DEPLOY_CONFIG" ]]; then
  accounts="$(jq -c '[.members[].account]' "$ENV_DEPLOY_CONFIG")"
else
  accounts='[]'
fi

{
  echo "# Generated by tools/gen-permissions.sh for the $ENV_NAME environment."
  echo "# Initial state only. The permissioning controller reconciles this file"
  echo "# against the on-chain MemberRegistry and reloads it in place."
  echo "#"
  echo "# Do not edit by hand: the controller overwrites it on every reconcile."
  echo ""
  echo "nodes-allowlist=$(echo "$nodes" | jq -r 'tostring')"
  echo "accounts-allowlist=$(echo "$accounts" | jq -r 'tostring')"
} > "$OUT"

echo "wrote $OUT"
echo "  nodes:    $(echo "$nodes" | jq 'length')"
echo "  accounts: $(echo "$accounts" | jq 'length')"
